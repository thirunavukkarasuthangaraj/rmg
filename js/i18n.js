  var EN = {};
  var nodes = [];

  function capture() {
    nodes = Array.prototype.slice.call(document.querySelectorAll("[data-i18n]"));
    nodes.forEach(function (el) {
      var k = el.getAttribute("data-i18n");
      if (!(k in EN)) EN[k] = el.innerHTML;
    });
  }

  function apply(lang) {
    var ta = lang === "ta";
    var dict = ta ? TA : EN;
    nodes.forEach(function (el) {
      var k = el.getAttribute("data-i18n");
      var v = dict[k];
      if (v == null) v = EN[k];           // graceful fallback to English
      if (v != null) el.innerHTML = v;
    });
    document.documentElement.setAttribute("lang", ta ? "ta" : "en");
    document.body.classList.toggle("lang-ta", ta);
    document.querySelectorAll(".lang-btn").forEach(function (b) {
      var on = b.getAttribute("data-lang") === lang;
      b.classList.toggle("active", on);
      b.setAttribute("aria-pressed", on ? "true" : "false");
    });
    try { localStorage.setItem("rmg_lang", lang); } catch (e) {}
  }

  document.addEventListener("DOMContentLoaded", function () {
    capture();
    document.querySelectorAll(".lang-btn").forEach(function (b) {
      b.addEventListener("click", function () { apply(b.getAttribute("data-lang")); });
    });
    var saved = "en";
    try { saved = localStorage.getItem("rmg_lang") || "en"; } catch (e) {}
    apply(saved);
  });
